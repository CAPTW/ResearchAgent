import fs from "node:fs";
import path from "node:path";
import { test, expect, topicA, installLedger, assertHygiene } from "./m2-paper-bank.real-backend.helpers";

test("unfinished human writing restores explicitly after sidecar restart without changing journal history", async ({ page, backend, context }, info) => {
  test.setTimeout(90000);
  const ledger = await installLedger(context, page);
  const runs = fs.readdirSync(path.join(backend.dataRoot, "runs")).sort();
  await page.goto(`/app/topics/${topicA}/papers`);
  await page.getByRole("table").locator("tbody input[type=checkbox]").first().check();
  await page.getByRole("button", { name: "선택 보고서 입력 고정" }).click();
  const panel = page.getByRole("region", { name: "선택 문헌 근거 초안" });
  await expect(panel.getByText("수동 진행 가능 · 0 / 3 단계")).toBeVisible();
  const job = new URL(page.url()).searchParams.get("synthesis")!;
  const root = `/api/topics/${topicA}/local-synthesis/${job}`;
  for (let step = 1; step <= 3; step++) {
    await panel.getByRole("button", { name: "다음 한 단계 실행" }).click();
    await expect(panel.getByText(`${step === 3 ? "근거 초안 준비됨" : "수동 진행 가능"} · ${step} / 3 단계`)).toBeVisible();
  }
  const reportBefore = await (await page.request.get(root + "/report")).json();
  await panel.getByText("근거 연결 검토 초안", { exact: true }).click();
  const editor = panel.getByRole("region", { name: "근거 연결 초안 편집" });
  const partial = "아직 인용과 제목을 정하지 않은 질문 e\u0301";
  await editor.getByLabel("검토 초안 제목").fill("");
  await editor.getByLabel("문장 1 분류").selectOption("question");
  await editor.getByLabel("문장 1 내용").fill(partial);
  await expect(editor.getByRole("button", { name: "검토 초안 새 버전 저장" })).toBeDisabled();
  await editor.getByText("작성 중 입력 보관·복구", { exact: true }).click();
  const working = editor.getByRole("region", { name: "작성 중 입력 보관과 복구" });
  await expect(working.getByText("현재 사용자에게 불러올 보관본이 없습니다.")).toBeVisible();
  await working.getByRole("button", { name: "현재 작성 중 입력 보관" }).click();
  await expect(working.getByText("요청 당시 입력을 보관했습니다.", { exact: false })).toBeVisible();
  const checkpoint = await (await page.request.get(root + "/journal-working-copy")).json();
  expect(checkpoint.copy.content).toEqual({ base_version_id: null, title: "", entries: [{ kind: "question", text: partial, citation_ids: [] }] });
  expect((await (await page.request.get(root + "/journal")).json()).total).toBe(0);
  await editor.getByLabel("문장 1 내용").fill("이 수정은 보관하지 않았다.");
  const url = page.url();
  await page.goto("about:blank"); await backend.restart(); await page.goto(url);
  await panel.getByText("근거 연결 검토 초안", { exact: true }).click();
  await expect(editor.getByLabel("문장 1 내용")).toHaveValue("");
  await editor.getByText("작성 중 입력 보관·복구", { exact: true }).click();
  await expect(working.getByText("마지막 확인한 보관 시각:", { exact: false })).toBeVisible();
  expect(await (await page.request.get(root + "/journal-working-copy")).json()).toEqual(checkpoint);
  await working.getByRole("button", { name: "현재 입력을 보관본으로 교체" }).click();
  await expect(editor.getByLabel("문장 1 내용")).toHaveValue(partial);
  await expect(editor.getByLabel("검토 초안 제목")).toHaveValue("");
  await expect(editor.getByRole("button", { name: "검토 초안 새 버전 저장" })).toBeDisabled();
  await working.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(process.env.XRML_REAL_BACKEND_PLAYWRIGHT_OUTPUT_DIR!, "journal-working-wide.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => { const b = await page.locator("#v2-sidebar").boundingBox(); return b ? b.x + b.width : 0; }).toBeLessThanOrEqual(0);
  await working.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(process.env.XRML_REAL_BACKEND_PLAYWRIGHT_OUTPUT_DIR!, "journal-working-narrow.png") });
  await editor.getByLabel("검토 초안 제목").fill("미완성 입력을 복구해 완성한 초안");
  await editor.getByText("문장 1 인용 선택", { exact: true }).click();
  await editor.getByRole("checkbox", { name: /· 초록$/ }).first().check();
  await editor.getByRole("button", { name: "검토 초안 새 버전 저장" }).click();
  await expect(panel.getByText("검토 초안 이력 · 1개 버전")).toBeVisible();
  const journal = await (await page.request.get(root + "/journal")).json();
  expect(journal.latest_version.entries[0].text).toBe(partial.normalize("NFC"));
  expect(await (await page.request.get(root + "/journal-working-copy")).json()).toEqual(checkpoint);
  await working.getByRole("button", { name: "불러올 보관본 해제" }).click();
  await expect(working.getByText("불러올 보관본을 해제했습니다.", { exact: false })).toBeVisible();
  await expect(editor.getByLabel("문장 1 내용")).toHaveValue(partial);
  const cleared = await (await page.request.get(root + "/journal-working-copy")).json();
  expect(cleared.copy).toBeNull(); expect(cleared.head_id).not.toBe(checkpoint.head_id);
  await page.goto("about:blank"); await backend.restart(); await page.goto(url);
  await panel.getByText("근거 연결 검토 초안", { exact: true }).click();
  await editor.getByText("작성 중 입력 보관·복구", { exact: true }).click();
  await expect(working.getByText("현재 사용자에게 불러올 보관본이 없습니다.")).toBeVisible();
  expect(await (await page.request.get(root + "/journal-working-copy")).json()).toEqual(cleared);
  expect(await (await page.request.get(root + "/journal")).json()).toEqual(journal);
  expect(await (await page.request.get(root + "/report")).json()).toEqual(reportBefore);
  await assertHygiene(ledger);
  expect(ledger.mutationRequests.every(value => value.includes("/local-synthesis"))).toBe(true);
  expect(fs.readdirSync(path.join(backend.dataRoot, "runs")).sort()).toEqual(runs);
  backend.writeJourneyResult({ journey: info.title, migrationIds: [], assertions: { partialCheckpoint: true, explicitRestore: true, restartPreserved: true, separateJournalVersion: true, releasedCheckpoint: true, unchangedReport: true, automaticRuns: 0, passed: info.status === "passed" }, timing: {}, hygiene: { consoleErrors: ledger.consoleErrors.length, pageErrors: ledger.pageErrors.length, offOriginAttempts: ledger.offOriginAttempts.length } });
});
