import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { test, expect, topicA, topicB, installLedger, assertHygiene } from "./m2-paper-bank.real-backend.helpers";

test("saved structured capture, evidence and human review survive lost response and restart", async ({ page, backend, context }, info) => {
  test.setTimeout(120000);
  const output = process.env.XRML_REAL_BACKEND_PLAYWRIGHT_OUTPUT_DIR!;
  let bundlePath = process.env.XRML_SAVED_ANALYSIS_BUNDLE_PATH;
  if (!bundlePath) {
    bundlePath = path.join(backend.root, "synthetic-capture.json");
    const seeded = spawnSync(backend.pythonExe, ["-c", "import json,sys;from tests.test_saved_analyses import bundle;from pathlib import Path;Path(sys.argv[1]).write_text(json.dumps(bundle(unsupported=True)),encoding='utf-8')", bundlePath], { cwd: backend.sourceRoot, env: process.env, encoding: "utf8", windowsHide: true, timeout: 30000 });
    expect(seeded.status, seeded.stderr).toBe(0);
  }
  const bundle = JSON.parse(fs.readFileSync(bundlePath, "utf8"));
  const packet = bundle.plan.contract.packet;
  const root = `/api/topics/${topicA}/saved-analyses`;
  const ledger = await installLedger(context, page);
  await page.goto(`/app/topics/${topicA}/papers`);
  const disclosure = page.getByText("저장된 분석 결과", { exact: true });
  await disclosure.focus(); await disclosure.press("Enter");
  await page.getByLabel("분석 응답 묶음 파일", { exact: true }).setInputFiles(bundlePath);
  await page.getByRole("button", { name: "구조화 응답 저장", exact: true }).click();
  const detail = page.getByRole("region", { name: "저장된 분석 상세", exact: true });
  await expect(detail.getByRole("heading", { name: "보존된 분석과 근거", exact: true })).toBeFocused();
  await expect(detail.getByText(packet.evidence_spans[0].text, { exact: true })).toBeVisible();
  const listing = await (await page.request.get(root)).json();
  expect(listing.total).toBe(1);
  const id = listing.items[0].analysis_id;
  const original = await (await page.request.get(`${root}/${id}`)).json();
  expect(original.bundle).toEqual(bundle);
  expect(original.receipt.packet).toEqual(packet);
  expect(original.receipt.status).toBe("needs_review");
  expect(original.decisions).toEqual([]);
  await page.getByLabel("분석 응답 묶음 파일", { exact: true }).setInputFiles(bundlePath);
  await page.getByRole("button", { name: "구조화 응답 저장", exact: true }).click();
  await expect(page.getByLabel("분석 응답 묶음 파일", { exact: true })).toBeEnabled();
  await expect(page.getByRole("button", { name: `분석 열기 · ${packet.paper_id}`, exact: true })).toHaveCount(1);
  const reviewUrl = `${root}/${id}/decisions`;
  const commands: string[] = [];
  let lose = true;
  await page.route(`**${reviewUrl}`, async route => {
    commands.push(route.request().postData()!);
    const result = await route.fetch();
    if (lose) { lose = false; await route.abort("failed"); }
    else await route.fulfill({ response: result });
  });
  await detail.getByLabel("분석 검토 메모", { exact: true }).fill("시험용 검토 메모: 발췌에 수치 결과 없음. e\u0301");
  await detail.getByLabel("분석 검토 상태", { exact: true }).selectOption("reviewed");
  await detail.getByRole("button", { name: "분석 검토 저장", exact: true }).click();
  await expect(detail.getByRole("alert")).toContainText("저장 결과를 확인하지 못했습니다");
  expect(commands).toHaveLength(1);
  await detail.getByRole("button", { name: "같은 검토 저장 재시도", exact: true }).click();
  await expect(detail.getByText("검토를 새 이력으로 저장했습니다.", { exact: true })).toBeVisible();
  expect(commands).toHaveLength(2); expect(commands[1]).toEqual(commands[0]);
  const saved = await (await page.request.get(`${root}/${id}`)).json();
  expect(saved.decisions).toHaveLength(1); expect(saved.bundle).toEqual(bundle);
  expect(saved.latest_decision.note).toBe("시험용 검토 메모: 발췌에 수치 결과 없음. e\u0301");
  // Human review marks in this disposable database are test data, not Owner adoption.
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator("#v2-sidebar").evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await detail.getByRole("heading", { name: "당시 보존된 근거", exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, "saved-analysis-narrow.png") });
  await backend.stop();
  await page.getByRole("button", { name: "분석 이력 새로고침", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("분석 이력을 불러오지 못했습니다");
  await expect(detail.getByText(packet.evidence_spans[0].text, { exact: true })).toBeVisible();
  await backend.start();
  await page.getByRole("button", { name: "분석 이력 새로고침", exact: true }).click();
  await expect(page.getByRole("alert")).toHaveCount(0);
  expect(await (await page.request.get(`${root}/${id}`)).json()).toEqual(saved);
  expect((await page.request.get(`${root}/${id}`.replace(topicA, topicB))).status()).toBe(404);
  await page.goto(`/app/topics/${topicB}/papers`);
  await expect(page.getByText(packet.evidence_spans[0].text, { exact: true })).toHaveCount(0);
  await page.goto(`/app/topics/${topicA}/papers`); await disclosure.click();
  await page.getByRole("button", { name: `분석 열기 · ${packet.paper_id}`, exact: true }).click();
  await expect(detail.getByLabel("분석 검토 메모", { exact: true })).toHaveValue(saved.latest_decision.note);
  await page.setViewportSize({ width: 1536, height: 1024 });
  await expect.poll(() => page.locator("#v2-sidebar").evaluate(element => Math.round(element.getBoundingClientRect().left))).toBe(0);
  await detail.getByRole("heading", { name: "보존된 분석과 근거", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, "saved-analysis-wide.png") });
  const expectedErrors = ledger.consoleErrors.splice(0);
  expect(expectedErrors.length).toBeGreaterThan(0);
  expect(expectedErrors.every(message => /ERR_FAILED|ERR_CONNECTION_REFUSED/.test(message))).toBe(true);
  ledger.handledExpectedErrors.push(...expectedErrors); await assertHygiene(ledger);
  expect(ledger.mutationRequests.every(request => request === `POST ${root}` || request === `POST ${reviewUrl}`)).toBe(true);
  fs.writeFileSync(path.join(output, "saved-analysis-observations.json"), JSON.stringify({ bundleSha: bundle.response_sha256, saved, ledger }, null, 2));
  backend.writeJourneyResult({ journey: info.title, migrationIds: [], assertions: { preservedCapture: true, duplicateImport: true, lostResponseReplay: true, restartEqual: true, noProviderCall: true, passed: info.status === "passed" }, timing: {}, hygiene: { consoleErrors: ledger.consoleErrors.length, pageErrors: ledger.pageErrors.length, offOriginAttempts: ledger.offOriginAttempts.length } });
});
