import fs from "node:fs";
import path from "node:path";
import { test, expect, topicA, installLedger, assertHygiene } from "./m2-paper-bank.real-backend.helpers";

test("user prepares a frozen journal request, cancels it and reopens exact history without execution", async ({ page, backend, context }, info) => {
  test.setTimeout(90000);
  const ledger = await installLedger(context, page);
  const runs = fs.readdirSync(path.join(backend.dataRoot, "runs")).sort();
  await page.goto(`/app/topics/${topicA}/papers`);
  await expect(page).toHaveURL(new RegExp(`/app/topics/${topicA}/papers`));
  await expect(page).not.toHaveTitle("");
  await page.getByRole("table").locator("tbody input[type=checkbox]").first().check();
  await page.getByRole("button", { name: "선택 보고서 입력 고정" }).click();
  const panel = page.getByRole("region", { name: "선택 문헌 근거 초안" });
  await expect(panel.getByText("수동 진행 가능 · 0 / 3 단계")).toBeVisible();
  const job = new URL(page.url()).searchParams.get("synthesis")!;
  const root = `/api/topics/${topicA}/local-synthesis/${job}`;
  for (let step = 1; step <= 3; step++) {
    await panel.getByRole("button", { name: "다음 한 단계 실행" }).click();
    await expect(panel.getByText(`${step === 3 ? "근거 초안 준비됨" : "수동 진행 가능"} · ${step} / 3 단계`)).toBeVisible();
  }
  await panel.getByText("저장된 생성 결과", { exact: true }).click();
  const results = page.getByRole("region", { name: "저장된 저널 생성 결과" });
  await expect(results.getByText(/저장된 실행 기록이 없습니다/)).toBeVisible();
  await results.getByText("새 생성 요청 준비", { exact: true }).click();
  const form = results.getByRole("form", { name: "생성 요청 준비" });
  await form.getByRole("radio", { name: "도구·모델 직접 입력" }).check();
  const model = form.getByLabel("요청 모델 이름");
  await form.getByRole("button", { name: "로컬 생성 요청 준비" }).click();
  expect(await model.evaluate((el: HTMLInputElement) => el.validity.valueMissing)).toBe(true);
  await model.fill("offline-requested-model");
  await form.getByLabel("최대 시도 횟수").fill("2");
  await form.getByLabel("시도당 출력 토큰 상한").fill("1024");
  const response = page.waitForResponse(r => r.url().endsWith(`${root}/journal-executions`) && r.request().method() === "POST");
  await form.getByRole("button", { name: "로컬 생성 요청 준비" }).click();
  const saved = (await (await response).json()).execution;
  expect(saved.contract.specification.model).toBe("offline-requested-model");
  expect(saved.current.state).toBe("READY"); expect(saved.current.attempt).toBe(0); expect(saved.events).toEqual([]);
  const url = `${root}/journal-executions/${saved.contract.execution_id}`;
  const history = results.getByRole("region", { name: "저널 실행 이력과 제어" });
  await expect(history.getByText(/최근 저장 상태: 입력 준비 기록 · 시도 0 \/ 최대 2회/)).toBeVisible();
  await expect(history.getByText(/금액 예산이 확인되었다는 뜻은 아닙니다/)).toBeVisible();
  await history.getByText("고정된 실행 요청 정보", { exact: true }).click();
  await expect(history.getByText("요청 도구·모델: openai · offline-requested-model")).toBeVisible();
  await expect(history.getByText("요청 출력 토큰 상한: 1024")).toBeVisible();
  await history.getByText("요청 내용·토큰 사용 기록", { exact: true }).click();
  await expect(history.getByText("저장된 호출 시도가 없습니다.")).toBeVisible();
  await history.getByText("보존된 어댑터 입력 보기", { exact: true }).click();
  expect(await history.getByLabel("보존된 문헌 입력").textContent()).toBe(saved.contract.provider_request.prompt);
  expect(await history.getByLabel("보존된 지시문").textContent()).toBe(saved.contract.provider_request.instructions);
  await history.getByText("요청 내용·토큰 사용 기록", { exact: true }).click();
  await expect(results.getByRole("button", { name: "검토 후보로 보존·열기" })).toHaveCount(0);
  await expect(page.getByText("주제 데이터를 불러오는 중입니다.", { exact: true })).not.toBeVisible();
  const artifacts = process.env.XRML_REAL_BACKEND_PLAYWRIGHT_OUTPUT_DIR!;
  await history.getByRole("heading").evaluate(el => el.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: path.join(artifacts, "journal-preparation-wide.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => { const box = await page.locator("#v2-sidebar").boundingBox(); return box ? box.x + box.width : 0; }).toBeLessThanOrEqual(0);
  await results.getByRole("button", { name: "다른 요청 준비" }).click();
  await form.getByLabel("요청 모델 이름").fill("pending-unsent-model");
  await form.getByRole("group").evaluate(el => el.scrollIntoView({ block: "center" }));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(artifacts, "journal-preparation-narrow.png") });
  await history.getByRole("button", { name: "이 요청의 결과 저장 취소" }).click();
  await expect(history.getByText(/최근 저장 상태: 결과 저장 취소 · 시도 0/)).toBeVisible();
  const cancelled = await (await page.request.get(url)).json();
  expect(cancelled.contract).toEqual(saved.contract);
  expect(cancelled.current.state).toBe("CANCELLED"); expect(cancelled.current.attempt).toBe(0);
  await page.goto("about:blank"); await backend.restart();
  expect(await (await page.request.get(url)).json()).toEqual(cancelled);
  expect((await (await page.request.get(`${root}/journal-executions`)).json()).total).toBe(1);
  await page.goto(`/app/topics/${topicA}/reports?synthesis=${encodeURIComponent(job)}`);
  await page.getByText("저장된 생성 결과", { exact: true }).click();
  await results.getByRole("button", { name: "실행 이력·제어 열기" }).click();
  await expect(history.getByText(/최근 저장 상태: 결과 저장 취소 · 시도 0/)).toBeVisible();
  await assertHygiene(ledger);
  expect(fs.readdirSync(path.join(backend.dataRoot, "runs")).sort()).toEqual(runs);
  backend.writeJourneyResult({ journey: info.title, migrationIds: [], assertions: { preparedViaUi: true, zeroAttempts: true, cancelled: true, restartPreserved: true, automaticRuns: 0, passed: info.status === "passed" }, timing: {}, hygiene: { consoleErrors: ledger.consoleErrors.length, pageErrors: ledger.pageErrors.length, offOriginAttempts: ledger.offOriginAttempts.length } });
});
