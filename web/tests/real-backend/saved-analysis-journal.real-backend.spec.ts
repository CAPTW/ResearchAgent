import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { test, expect, topicA, topicB, installLedger, assertHygiene } from './m2-paper-bank.real-backend.helpers';

test('private saved analysis produces a frozen reviewed journal without a new model call', async ({ page, backend, context }, info) => {
  test.setTimeout(120000);
  const output = process.env.XRML_REAL_BACKEND_PLAYWRIGHT_OUTPUT_DIR!;
  let bundlePath = process.env.XRML_SAVED_ANALYSIS_BUNDLE_PATH;
  if (!bundlePath) {
    bundlePath = path.join(backend.root, 'synthetic-capture.json');
    const result = spawnSync(backend.pythonExe, ['-c', "import json,sys;from tests.test_saved_analyses import bundle;from pathlib import Path;Path(sys.argv[1]).write_text(json.dumps(bundle(unsupported=True)),encoding='utf-8')", bundlePath], { cwd: backend.sourceRoot, env: process.env, encoding: 'utf8', windowsHide: true, timeout: 30000 });
    expect(result.status, result.stderr).toBe(0);
  }
  const original = JSON.parse(fs.readFileSync(bundlePath, 'utf8'));
  const ledger = await installLedger(context, page);
  await page.goto(`/app/topics/${topicA}/papers`);
  await page.getByText('저장된 분석 결과', { exact: true }).click();
  await page.getByLabel('분석 응답 묶음 파일', { exact: true }).setInputFiles(bundlePath);
  await page.getByRole('button', { name: '구조화 응답 저장', exact: true }).click();
  const archive = page.getByRole('region', { name: '저장된 분석 상세', exact: true });
  await expect(archive.getByRole('heading', { name: '보존된 분석과 근거' })).toBeFocused();
  const disclosure = archive.getByText('분석으로 Journal 후보 만들기', { exact: true });
  await disclosure.focus(); await disclosure.press('Enter');
  const workspace = archive.getByRole('region', { name: '분석 Journal 후보 작업' });
  await workspace.getByLabel('기여 요약 선택', { exact: true }).check();
  await expect(workspace.getByRole('button', { name: '선택 분석으로 후보 저장' })).toBeDisabled();
  await archive.getByLabel('분석 검토 상태', { exact: true }).selectOption('reviewed');
  await archive.getByLabel('분석 검토 메모', { exact: true }).fill('시험용 확인: 공개 논문 발췌만 확인, Owner의 연구 채택 아님.');
  await archive.getByRole('button', { name: '분석 검토 저장', exact: true }).click();
  await expect(workspace.getByRole('button', { name: '선택 분석으로 후보 저장' })).toBeEnabled();
  const analysisRoot = `/api/topics/${topicA}/saved-analyses`;
  const saved = (await (await page.request.get(analysisRoot)).json()).items[0];
  const root = `${analysisRoot}/${saved.analysis_id}/journals`;
  let lose = true;
  const commands: string[] = [];
  await page.route(`**${root}`, async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    commands.push(route.request().postData()!);
    const result = await route.fetch();
    if (lose) { lose = false; await route.abort('failed'); } else await route.fulfill({ response: result });
  });
  await workspace.getByRole('button', { name: '선택 분석으로 후보 저장', exact: true }).click();
  await expect(workspace.getByRole('alert')).toContainText('저장 결과를 확인하지 못했습니다');
  expect(commands).toHaveLength(1);
  await workspace.getByRole('button', { name: '같은 후보 저장 재시도', exact: true }).click();
  const candidate = workspace.getByRole('article', { name: '분석에서 만든 Journal 후보', exact: true });
  const editor = candidate.getByRole('region', { name: '저널 근거 판단 편집' });
  await expect(editor.getByLabel('문장 1 근거 판단')).toBeVisible();
  expect(commands).toHaveLength(2); expect(commands[0]).toEqual(commands[1]);
  expect((await (await page.request.get(root)).json()).total).toBe(1);
  await expect(editor.getByRole('button', { name: '저널로 채택', exact: true })).toBeDisabled();
  await editor.getByText(/^검토 근거 ·/).click();
  await expect(editor.getByText(original.plan.contract.packet.evidence_spans[0].text, { exact: true })).toBeVisible();
  await editor.getByLabel('문장 1 근거 판단').selectOption('limited');
  await editor.getByLabel('문장 1 검토 메모').fill('일부 발췌의 해석이며 전문 검토는 미확인. e\u0301');
  await editor.getByLabel('저널 전체 검토 메모').fill('시험용 채택 기록; 실제 연구 승인 아님.');
  await editor.getByRole('button', { name: '검토 내용 저장', exact: true }).click();
  await expect(candidate.getByText('현재 사람의 검토 상태: 검토 중', { exact: true })).toBeVisible();
  await editor.getByRole('button', { name: '저널로 채택', exact: true }).click();
  await expect(candidate.getByText('현재 사람의 검토 상태: 저널로 채택', { exact: true })).toBeVisible();
  const review = candidate.getByRole('article', { name: '보존된 저널 검토 기록' });
  const [download] = await Promise.all([page.waitForEvent('download'), review.getByRole('button', { name: '채택 저널 검토·근거 JSON 내려받기' }).click()]);
  const exportedPath = path.join(output, 'saved-analysis-journal.json'); await download.saveAs(exportedPath);
  const exported = JSON.parse(fs.readFileSync(exportedPath, 'utf8'));
  expect(exported.candidate.source.response_sha256).toBe(original.response_sha256);
  expect(exported.candidate.source.receipt.status).toBe('needs_review');
  expect(exported.candidate.source.receipt.packet).toEqual(original.plan.contract.packet);
  expect(exported.candidate.proposal.sections[0].entries[0].kind).toBe('interpretation');
  expect(exported.review.report.content).toContain('새 모델 호출 없이');
  expect(exported.review.report.content).toContain('문장별 뒷받침은 미확인');
  expect(exported.candidate).not.toHaveProperty('job_id');
  const candidateUrl = `${root}/${exported.candidate.candidate_id}`;
  const exportUrl = `${candidateUrl}/reviews/${exported.review.review_id}/export?format=json`;
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator('#v2-sidebar').evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await candidate.getByRole('heading', { name: '보존된 분석의 검토 원고', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'analysis-journal-narrow.png') });
  await page.goto('about:blank'); await backend.restart();
  await page.goto(`/app/topics/${topicA}/papers`);
  await page.getByText('저장된 분석 결과', { exact: true }).click();
  await page.getByRole('button', { name: `분석 열기 · ${original.plan.contract.packet.paper_id}`, exact: true }).click();
  await disclosure.click();
  await workspace.getByRole('button', { name: /^후보 열기/ }).click();
  await expect(candidate.getByText('현재 사람의 검토 상태: 저널로 채택', { exact: true })).toBeVisible();
  expect(JSON.parse((await (await page.request.get(exportUrl)).json()).content)).toEqual(exported);
  expect((await page.request.get(candidateUrl.replace(topicA, topicB))).status()).toBe(404);
  // Source rejection blocks new use, but actual saved history remains navigable.
  await archive.getByLabel('분석 검토 상태', { exact: true }).selectOption('rejected');
  await archive.getByRole('button', { name: '분석 검토 저장', exact: true }).click();
  await expect(candidate.getByText(/분석의 검토 기준이 바뀌어/)).toBeVisible();
  await candidate.getByRole('button', { name: new RegExp(`저널로 채택 ·.*${exported.review.review_id}`) }).click();
  await expect(review.getByText('보존 판단: 저널로 채택', { exact: true })).toBeVisible();
  await expect(review.getByRole('button', { name: '채택 저널 검토·근거 JSON 내려받기' })).toBeDisabled();
  await candidate.getByRole('button', { name: '검토 2번을 비교 기준으로 선택' }).click();
  await expect(candidate.getByText('판단·메모 변경 0 / 1문장 · 동일 1문장', { exact: true })).toBeVisible();
  expect((await page.request.get(exportUrl)).status()).toBe(409);
  await page.setViewportSize({ width: 1536, height: 1024 });
  await expect.poll(() => page.locator('#v2-sidebar').evaluate(element => Math.round(element.getBoundingClientRect().left))).toBe(0);
  await candidate.getByRole('heading', { name: '보존된 분석의 검토 원고', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'analysis-journal-wide.png') });
  const expectedErrors = ledger.consoleErrors.splice(0);
  expect(expectedErrors.length).toBeGreaterThan(0);
  expect(expectedErrors.every(message => /ERR_FAILED/.test(message))).toBe(true);
  ledger.handledExpectedErrors.push(...expectedErrors); await assertHygiene(ledger);
  expect(ledger.mutationRequests.every(request => request.startsWith(`POST ${analysisRoot}`))).toBe(true);
  fs.writeFileSync(path.join(output, 'observations.json'), JSON.stringify({ captureSha: original.response_sha256, candidateId: exported.candidate.candidate_id, reviewId: exported.review.review_id, ledger }, null, 2));
  backend.writeJourneyResult({ journey: info.title, migrationIds: [], assertions: { explicitSelection: true, noNewProviderCall: true, duplicateReplay: true, separateAdoption: true, restartEqual: true, staleSourceReadOnly: true, passed: info.status === 'passed' }, timing: {}, hygiene: { consoleErrors: ledger.consoleErrors.length, pageErrors: ledger.pageErrors.length, offOriginAttempts: ledger.offOriginAttempts.length } });
});
