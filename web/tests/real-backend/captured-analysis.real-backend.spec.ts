import fs from 'node:fs';
import path from 'node:path';
import { test, expect, topicA, topicB, installLedger, assertHygiene } from './m2-paper-bank.real-backend.helpers';

test.use({ capturedAnalysisFixture: true });

test('app capture saves once and remains reviewable through journal export and restart', async ({ page, backend, context }, info) => {
  test.setTimeout(120000);
  const output = process.env.XRML_REAL_BACKEND_PLAYWRIGHT_OUTPUT_DIR!;
  const trialPath = path.join(backend.dataRoot, 'captured-trial.json');
  const originalBytes = fs.readFileSync(trialPath);
  const original = JSON.parse(originalBytes.toString('utf8'));
  const ledger = await installLedger(context, page);
  const analysisRoot = `/api/topics/${topicA}/saved-analyses`;
  const sourceUrl = `${analysisRoot}/sources/anthropic-trial`;
  let sourceReads = 0;
  page.on('request', request => { if (request.url().endsWith(sourceUrl) && request.method() === 'GET') sourceReads++; });
  await page.goto(`/app/topics/${topicA}/papers`);
  await page.getByText('저장된 분석 결과', { exact: true }).click();
  const capture = page.getByRole('region', { name: '앱 보존 응답 저장' });
  const inspect = capture.getByRole('button', { name: '앱에 보존된 성공 응답 확인', exact: true });
  await expect(inspect).toBeEnabled();
  expect(sourceReads).toBe(0);
  await inspect.focus(); await inspect.press('Enter');
  await expect(capture.getByText('합성 fixture 발췌 · 실제 AI 연구 실행의 증거가 아닙니다.', { exact: true })).toBeVisible();
  await expect(capture.getByText(original.binding.grant.source.excerpt, { exact: true })).toBeVisible();
  expect(sourceReads).toBe(1);
  let lose = true;
  const commands: string[] = [];
  await page.route(`**${sourceUrl}`, async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    commands.push(route.request().postData()!);
    const result = await route.fetch();
    if (lose) { lose = false; await route.abort('failed'); } else await route.fulfill({ response: result });
  });
  await capture.getByRole('button', { name: '이 주제에 분석 저장', exact: true }).click();
  await expect(capture.getByRole('alert')).toContainText('저장 결과를 확인하지 못했습니다');
  expect(commands).toHaveLength(1);
  await expect(inspect).toBeDisabled();
  await capture.getByRole('button', { name: '같은 응답 저장 다시 확인', exact: true }).click();
  const archive = page.getByRole('region', { name: '저장된 분석 상세', exact: true });
  await expect(archive.getByRole('heading', { name: '보존된 분석과 근거', exact: true })).toBeFocused();
  await expect(archive.getByText(/^합성 실행의 앱 보존 사본입니다/)).toBeVisible();
  await expect(archive.getByText(/^캡처 시각 \(앱 보존 기록\)/)).toBeVisible();
  expect(commands).toHaveLength(2); expect(commands[0]).toBe(commands[1]);
  const listing = await (await page.request.get(analysisRoot)).json();
  expect(listing.total).toBe(1);
  const detailUrl = `${analysisRoot}/${listing.items[0].analysis_id}`;
  const saved = await (await page.request.get(detailUrl)).json();
  expect(saved.bundle.plan).toEqual(original.binding);
  expect(saved.bundle.events).toEqual(original.events);
  expect(saved.latest_decision).toBeNull();
  expect(saved.receipt.input_origin).toBe('FIXTURE_SYNTHETIC_CAPTURE');
  await archive.getByText('분석으로 Journal 후보 만들기', { exact: true }).click();
  const workspace = archive.getByRole('region', { name: '분석 Journal 후보 작업' });
  await workspace.getByLabel('기여 요약 선택', { exact: true }).check();
  await expect(workspace.getByRole('button', { name: '선택 분석으로 후보 저장' })).toBeDisabled();
  await archive.getByLabel('분석 검토 상태', { exact: true }).selectOption('reviewed');
  await archive.getByLabel('분석 검토 메모', { exact: true }).fill('합성 시험의 일부 발췌만 확인. 실제 연구 채택 아님.');
  await archive.getByRole('button', { name: '분석 검토 저장', exact: true }).click();
  await workspace.getByRole('button', { name: '선택 분석으로 후보 저장', exact: true }).click();
  const candidate = workspace.getByRole('article', { name: '분석에서 만든 Journal 후보', exact: true });
  const editor = candidate.getByRole('region', { name: '저널 근거 판단 편집' });
  await expect(editor.getByRole('button', { name: '저널로 채택', exact: true })).toBeDisabled();
  await editor.getByText(/^검토 근거 ·/).click();
  await expect(editor.getByText(original.binding.grant.source.excerpt, { exact: true })).toBeVisible();
  await editor.getByLabel('문장 1 근거 판단').selectOption('limited');
  await editor.getByLabel('문장 1 검토 메모').fill('합성 응답, 전문 검토 미확인. e\u0301');
  await editor.getByRole('button', { name: '검토 내용 저장', exact: true }).click();
  await expect(candidate.getByText('현재 사람의 검토 상태: 검토 중', { exact: true })).toBeVisible();
  await editor.getByRole('button', { name: '저널로 채택', exact: true }).click();
  const review = candidate.getByRole('article', { name: '보존된 저널 검토 기록' });
  const [download] = await Promise.all([page.waitForEvent('download'), review.getByRole('button', { name: '채택 저널 검토·근거 JSON 내려받기' }).click()]);
  const exportedPath = path.join(output, 'captured-analysis-journal.json'); await download.saveAs(exportedPath);
  const exported = JSON.parse(fs.readFileSync(exportedPath, 'utf8'));
  expect(exported.candidate.source.response_sha256).toBe(saved.bundle.response_sha256);
  expect(exported.candidate.source.receipt.input_origin).toBe('FIXTURE_SYNTHETIC_CAPTURE');
  expect(exported.review.report.content).toContain('앱 보존 기록');
  const exportUrl = `${detailUrl}/journals/${exported.candidate.candidate_id}/reviews/${exported.review.review_id}/export?format=json`;
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator('#v2-sidebar').evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await capture.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'captured-analysis-narrow.png') });
  const preserved = await (await page.request.get(detailUrl)).json();
  await page.goto('about:blank'); await backend.restart();
  await page.goto(`/app/topics/${topicA}/papers`);
  await page.getByText('저장된 분석 결과', { exact: true }).click();
  await page.getByRole('button', { name: `분석 열기 · ${saved.receipt.paper_id}`, exact: true }).click();
  await expect(archive.getByText('현재 사람의 상태: 직접 확인함. 직접 확인 표시는 과학적 검증이나 저널 채택을 뜻하지 않습니다.', { exact: true })).toBeVisible();
  expect(await (await page.request.get(detailUrl)).json()).toEqual(preserved);
  expect(JSON.parse((await (await page.request.get(exportUrl)).json()).content)).toEqual(exported);
  expect((await page.request.get(detailUrl.replace(topicA, topicB))).status()).toBe(404);
  await page.goto(`/app/topics/${topicB}/papers`);
  await page.getByText('저장된 분석 결과', { exact: true }).click();
  await expect(page.getByText('저장된 분석이 없습니다.', { exact: true })).toBeVisible();
  expect((await (await page.request.get(analysisRoot.replace(topicA, topicB))).json()).total).toBe(0);
  expect(sourceReads).toBe(1);
  expect(fs.readFileSync(trialPath).equals(originalBytes)).toBe(true);
  expect(JSON.parse(fs.readFileSync(path.join(backend.dataRoot, 'capture-seed.json'), 'utf8'))).toEqual({ synthetic_calls: 1, live_calls: 0 });
  const expectedErrors = ledger.consoleErrors.splice(0);
  expect(expectedErrors.length).toBeGreaterThan(0);
  expect(expectedErrors.every(message => /ERR_FAILED/.test(message))).toBe(true);
  ledger.handledExpectedErrors.push(...expectedErrors); await assertHygiene(ledger);
  expect(ledger.mutationRequests.every(request => request.startsWith(`POST ${analysisRoot}`))).toBe(true);
  fs.writeFileSync(path.join(output, 'capture-observations.json'), JSON.stringify({ analysisId: saved.analysis_id, sourceReads, commands, ledger, originalTrialUnchanged: true, syntheticCalls: 1, liveCalls: 0 }, null, 2));
  backend.writeJourneyResult({ journey: info.title, migrationIds: [], assertions: { noFileImport: true, explicitSave: true, duplicateReplay: true, separateHumanAdoption: true, restartEqual: true, topicIsolated: true, originalTrialUnchanged: true, passed: info.status === 'passed' }, timing: {}, hygiene: { consoleErrors: ledger.consoleErrors.length, pageErrors: ledger.pageErrors.length, offOriginAttempts: ledger.offOriginAttempts.length } });
});
