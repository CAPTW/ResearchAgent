def render_claude_skill(contract: CanonicalContract) -> str:
    frontmatter, body = _split_frontmatter(contract.canonical_skill)
    if frontmatter:
        return f"{frontmatter}\n\n{AUTOGENERATED_NOTICE}\n\n{body.strip()}\n"
    return f"{AUTOGENERATED_NOTICE}\n\n{contract.canonical_skill.strip()}\n"


def expected_generated_files(repo_root: Path) -> dict[Path, str]:
    contract = load_canonical_contract(repo_root)
    return {
        repo_root / "GEMINI.md": render_gemini_md(contract),
        repo_root / "CLAUDE.md": render_claude_md(contract),
        repo_root / ".claude" / "skills" / "local-research-run" / "SKILL.md": render_claude_skill(contract),
        repo_root / ".claude" / "rules" / "local-only.md": render_claude_rule_local_only(contract),
        repo_root / ".claude" / "rules" / "reporting.md": render_claude_rule_reporting(contract),
    }


def diff_summary(existing: str, desired: str, path: Path) -> str:
    diff_lines = list(
        difflib.unified_diff(
            existing.splitlines(),
            desired.splitlines(),
            fromfile=str(path),
            tofile=f"{path} (generated)",
            lineterm="",
            n=1,
        )
    )
    return "\n".join(diff_lines[:20])


def sync_generated_files(repo_root: Path, *, write: bool) -> list[FileChange]:
    changes: list[FileChange] = []
    for path, desired in expected_generated_files(repo_root).items():
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        if existing == desired:
            continue
        status = "create" if existing is None else "update"
        changes.append(FileChange(path=path, status=status))
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(desired, encoding="utf-8")
    return changes


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate thin Gemini/Claude adapter files from the canonical local workflow core.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--diff-summary", action="store_true")
    parser.add_argument("--repo-root", default="", help="Override repo root for tests or dry validation.")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    repo_root = Path(args.repo_root).resolve() if str(args.repo_root).strip() else Path(__file__).resolve().parents[1]

    try:
        if args.write:
            changes = sync_generated_files(repo_root, write=True)
            if not changes:
                print("Adapter files are up to date.")
            else:
                for change in changes:
                    print(f"{change.status}: {change.path.relative_to(repo_root)}")
            return 0

        expected = expected_generated_files(repo_root)
        changes = sync_generated_files(repo_root, write=False)
        if args.check:
            if changes:
                for change in changes:
                    print(f"{change.status}: {change.path.relative_to(repo_root)}")
                return 1
            print("Adapter files are in sync.")
            return 0

        if args.diff_summary:
            if not changes:
                print("Adapter files are up to date.")
                return 0
            for change in changes:
                path = change.path
                existing = path.read_text(encoding="utf-8") if path.is_file() else ""
                print(f"== {change.status}: {path.relative_to(repo_root)} ==")
                print(diff_summary(existing, expected[path], path))
            return 0

        parser.error("No mode selected.")
        return 2
    except SyncError as exc:
        print(f"error: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
