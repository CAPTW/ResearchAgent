AUTOGENERATED_NOTICE = "<!-- AUTOGENERATED: run `uv run python tools/sync_agent_adapters.py --write`. Do not edit manually. -->"
CANONICAL_OUTPUT_FIELDS = ("status", "run_id", "provider_mode", "artifact_paths", "local_ui_urls", "failures", "executed_via")


class SyncError(RuntimeError):
    pass


@dataclass(frozen=True)
class CanonicalContract:
    repo_root: Path
    input_flags: tuple[str, ...]
    output_fields: tuple[str, ...]
    policy_phrases: tuple[str, ...]
    canonical_skill: str

    @property
    def runner_command(self) -> str:
        return 'uv run python tools/local_research_workflow.py --topic "<topic>" --profile-name "<profile>"'

    @property
    def powershell_wrapper(self) -> str:
        return 'pwsh scripts/run_local_research.ps1 --topic "<topic>" --profile-name "<profile>"'

    @property
    def bash_wrapper(self) -> str:
        return 'bash scripts/run_local_research.sh --topic "<topic>" --profile-name "<profile>"'

    @property
    def mcp_server_command(self) -> str:
        return "uv run python tools/local_research_mcp_server.py"


@dataclass(frozen=True)
class FileChange:
    path: Path
    status: str


def _read_text(path: Path) -> str:
    if not path.is_file():
        raise SyncError(f"Missing required canonical file: {path}")
    return path.read_text(encoding="utf-8")


def _extract_section_list(text: str, section: str) -> list[str]:
    pattern = rf"### {re.escape(section)}\n(?P<body>(?:- .+\n)+)"
    match = re.search(pattern, text)
    if not match:
        raise SyncError(f"Could not find Canonical Adapter Contract section: {section}")
    body = match.group("body")
    items: list[str] = []
    for line in body.splitlines():
        if not line.startswith("- "):
            continue
        raw_value = line[2:].strip()
        code_match = re.search(r"`([^`]+)`", raw_value)
        items.append(code_match.group(1) if code_match else raw_value)
    return items


def _validate_runner_flags(input_flags: list[str]) -> None:
    parser = build_local_workflow_parser()
    runner_flags = {
        option
        for action in parser._actions
        for option in action.option_strings
        if option.startswith("--")
    }
    missing = [flag for flag in input_flags if flag.startswith("--") and flag not in runner_flags]
    if missing:
        raise SyncError(f"Canonical docs mention flags not supported by the runner: {', '.join(missing)}")


def load_canonical_contract(repo_root: Path) -> CanonicalContract:
    agents_text = _read_text(repo_root / "AGENTS.md")
    docs_text = _read_text(repo_root / "docs" / "LOCAL_RESEARCH_WORKFLOW.md")
    skill_text = _read_text(repo_root / ".agents" / "skills" / "local-research-run" / "SKILL.md")

    required_agents_phrases = (
        "local-only research workflow",
        "fallback_only",
        "public OAuth/Render/staging",
    )
    lowered_agents = agents_text.lower()
    missing_agents = [phrase for phrase in required_agents_phrases if phrase.lower() not in lowered_agents]
    if missing_agents:
        raise SyncError(f"AGENTS.md is missing required local adapter phrases: {', '.join(missing_agents)}")

    input_flags = _extract_section_list(docs_text, "Inputs")
    output_fields = _extract_section_list(docs_text, "Outputs")
    policy_phrases = _extract_section_list(docs_text, "Fixed policy phrases")

    _validate_runner_flags(input_flags)
    missing_outputs = [field for field in CANONICAL_OUTPUT_FIELDS if field not in output_fields]
    if missing_outputs:
        raise SyncError(f"Canonical docs are missing required output fields: {', '.join(missing_outputs)}")

    return CanonicalContract(
        repo_root=repo_root,
        input_flags=tuple(input_flags),
        output_fields=tuple(output_fields),
        policy_phrases=tuple(policy_phrases),
        canonical_skill=skill_text,
    )


def _split_frontmatter(markdown_text: str) -> tuple[str, str]:
    if not markdown_text.startswith("---\n"):
        return "", markdown_text
    end_index = markdown_text.find("\n---\n", 4)
    if end_index == -1:
        return "", markdown_text
    frontmatter = markdown_text[: end_index + 5].strip()
    body = markdown_text[end_index + 5 :].lstrip()
    return frontmatter, body


