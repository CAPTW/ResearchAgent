from __future__ import annotations

from pathlib import Path

from tools.sync_agent_adapters import _split_frontmatter, main, sync_generated_files


REPO_ROOT = Path(__file__).resolve().parents[1]
CANONICAL_FILES = (
    Path("AGENTS.md"),
    Path("docs/LOCAL_RESEARCH_WORKFLOW.md"),
    Path(".agents/skills/local-research-run/SKILL.md"),
)
GENERATED_FILES = (
    Path("GEMINI.md"),
    Path("CLAUDE.md"),
    Path(".claude/skills/local-research-run/SKILL.md"),
    Path(".claude/rules/local-only.md"),
    Path(".claude/rules/reporting.md"),
)


def _seed_canonical_core(temp_root: Path) -> None:
    for relative_path in CANONICAL_FILES:
        source = REPO_ROOT / relative_path
        destination = temp_root / relative_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")


def test_sync_agent_adapters_generates_required_files(tmp_path: Path) -> None:
    _seed_canonical_core(tmp_path)

    changes = sync_generated_files(tmp_path, write=True)

    assert changes
    for relative_path in GENERATED_FILES:
        generated_path = tmp_path / relative_path
        assert generated_path.is_file()
        assert "AUTOGENERATED" in generated_path.read_text(encoding="utf-8")


def test_sync_agent_adapters_is_idempotent(tmp_path: Path) -> None:
    _seed_canonical_core(tmp_path)

    first_changes = sync_generated_files(tmp_path, write=True)
    second_changes = sync_generated_files(tmp_path, write=True)

    assert first_changes
    assert second_changes == []


def test_generated_adapter_docs_include_canonical_prohibitions() -> None:
    gemini_text = (REPO_ROOT / "GEMINI.md").read_text(encoding="utf-8")
    claude_text = (REPO_ROOT / "CLAUDE.md").read_text(encoding="utf-8")

    required_phrases = (
        "local-only",
        "do not touch Render/public OAuth/staging",
        "fallback_only is acceptable without OPENAI_API_KEY",
        "report only: status, run_id, provider_mode, artifact_paths, local_ui_urls, failures, executed_via",
        "run_local_research",
        "Never report success without a real `run_id`.",
    )

    for phrase in required_phrases:
        assert phrase in gemini_text
        assert phrase in claude_text


def test_claude_mirror_skill_stays_in_sync_with_canonical_skill() -> None:
    canonical_text = (REPO_ROOT / ".agents/skills/local-research-run/SKILL.md").read_text(encoding="utf-8")
    mirror_text = (REPO_ROOT / ".claude/skills/local-research-run/SKILL.md").read_text(encoding="utf-8")
    _, canonical_body = _split_frontmatter(canonical_text)

    assert canonical_body.strip() in mirror_text
    for field in ("status", "run_id", "provider_mode", "artifact_paths", "local_ui_urls", "failures", "executed_via"):
        assert f"`{field}`" in mirror_text


def test_agent_adapters_doc_points_to_real_files_and_commands() -> None:
    doc_text = (REPO_ROOT / "docs/AGENT_ADAPTERS.md").read_text(encoding="utf-8")

    required_paths = (
        "tools/local_research_workflow.py",
        "tools/local_research_mcp_server.py",
        "scripts/run_local_research.ps1",
        "scripts/run_local_research.sh",
        "tools/sync_agent_adapters.py",
        "GEMINI.md",
        "CLAUDE.md",
    )
    required_commands = (
        "uv run python tools/sync_agent_adapters.py --check",
        "python tools/sync_agent_adapters.py --check",
        "pwsh scripts/sync_agent_adapters.ps1 --check",
        "bash scripts/sync_agent_adapters.sh --check",
        "pwsh scripts/run_local_research.ps1 --topic \"Gaussian avatars in XR\" --profile-name \"Gaussian XR\"",
    )

    for relative_path in required_paths:
        assert relative_path in doc_text
        assert (REPO_ROOT / relative_path).exists()
    for command in required_commands:
        assert command in doc_text


def test_sync_agent_adapters_check_passes_for_repo_state() -> None:
    assert main(["--check", "--repo-root", str(REPO_ROOT)]) == 0
